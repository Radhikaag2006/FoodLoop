"""Hash-chained disposal records + PDF.

Each record stores sha256(prev_hash + canonical payload). Editing any
past record breaks every later hash, which /verify detects. This is a
simple tamper-evident log, not a blockchain, and not an official
FSSAI certificate.
"""
import hashlib
import io
import json
from datetime import datetime

import segno
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen import canvas

from .tiers import tier_letter
from sqlalchemy import select

from .models import Record, Pickup, PickupLine, Facility, Org
from .clock import utcnow
from .config import DEMO_MODE


def _hash(prev, payload_json):
    data = (prev + payload_json).encode()
    return hashlib.sha256(data).hexdigest()


def create_record(db, pickup):
    fac = db.get(Facility, pickup.facility_id)
    lines = []
    q = select(PickupLine).where(PickupLine.pickup_id == pickup.id)
    for ln in db.scalars(q):
        org = db.get(Org, ln.org_id)
        lines.append({
            "source": org.name, "kind": ln.ref_type,
            "ref": ln.ref_id, "tier": ln.tier,
            "kg": round(ln.kg, 2),
        })
    n = db.scalars(select(Record)).all()
    code = f"FL-{utcnow().year}-{len(n) + 1:05d}"
    payload = {
        "code": code,
        "pickup_id": pickup.id,
        "facility": {"name": fac.name, "kind": fac.kind,
                     "certified": fac.certified},
        "lines": lines,
        "expected_kg": pickup.expected_kg,
        "hub_kg": pickup.hub_kg,
        "facility_kg": pickup.facility_kg,
        "mismatch": pickup.mismatch,
        "closed_at": pickup.closed_at.isoformat(timespec="seconds"),
    }
    pj = json.dumps(payload, sort_keys=True)
    last = db.scalars(
        select(Record).order_by(Record.id.desc())).first()
    prev = last.hash if last else ""
    rec = Record(pickup_id=pickup.id, code=code, payload=pj,
                 prev_hash=prev, hash=_hash(prev, pj))
    db.add(rec)
    db.commit()
    return rec


def verify_record(db, rec):
    """Recompute this record's hash and check its link to the chain."""
    own_ok = _hash(rec.prev_hash, rec.payload) == rec.hash
    prev = db.scalars(
        select(Record).where(Record.id < rec.id)
        .order_by(Record.id.desc())).first()
    link_ok = (prev.hash if prev else "") == rec.prev_hash
    return {"hash_ok": own_ok, "chain_ok": link_ok,
            "valid": own_ok and link_ok}


def record_pdf(rec, base_url):
    d = json.loads(rec.payload)
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4)
    w, h = A4
    green = colors.HexColor("#14532d")
    c.setFillColor(green)
    c.rect(0, h - 28 * mm, w, 28 * mm, fill=1, stroke=0)
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 20)
    c.drawString(18 * mm, h - 15 * mm, "FoodLoop Disposal Record")
    c.setFont("Helvetica", 10)
    c.drawString(18 * mm, h - 22 * mm, d["code"])

    c.setFillColor(colors.black)
    y = h - 40 * mm
    c.setFont("Helvetica-Bold", 11)
    c.drawString(18 * mm, y, "Facility")
    c.setFont("Helvetica", 10)
    cert = "certified" if d["facility"]["certified"] else "not certified"
    y -= 6 * mm
    c.drawString(18 * mm, y, f'{d["facility"]["name"]} ({cert})')
    y -= 9 * mm
    c.setFont("Helvetica-Bold", 11)
    c.drawString(18 * mm, y, "Weights (kg)")
    c.setFont("Helvetica", 10)
    y -= 6 * mm
    line = (f'Expected {d["expected_kg"]}  |  Hub {d["hub_kg"]}  |  '
            f'Facility {d["facility_kg"]}')
    c.drawString(18 * mm, y, line)
    y -= 6 * mm
    flag = "Mismatch flagged" if d["mismatch"] else "Within tolerance"
    c.drawString(18 * mm, y, f"Weight check: {flag}")
    y -= 10 * mm
    c.setFont("Helvetica-Bold", 11)
    c.drawString(18 * mm, y, "Collected from")
    c.setFont("Helvetica", 9)
    y -= 6 * mm
    for ln in d["lines"][:28]:
        txt = (f'{ln["source"]}  |  {ln["kind"]} #{ln["ref"]}  |  '
               f'tier {tier_letter(ln["tier"])}  |  {ln["kg"]} kg')
        c.drawString(18 * mm, y, txt)
        y -= 5 * mm
        if y < 60 * mm:
            break

    url = f"{base_url}/verify/{d['code']}"
    qr = segno.make(url, error="m")
    qb = io.BytesIO()
    qr.save(qb, kind="png", scale=4)
    qb.seek(0)
    c.drawImage(ImageReader(qb), w - 52 * mm, 20 * mm,
                width=32 * mm, height=32 * mm)
    c.setFont("Helvetica", 7)
    c.drawString(18 * mm, 40 * mm, "Record hash:")
    c.drawString(18 * mm, 36 * mm, rec.hash)
    c.drawString(18 * mm, 32 * mm, "Previous hash:")
    c.drawString(18 * mm, 28 * mm, rec.prev_hash or "(first record)")
    c.setFont("Helvetica-Oblique", 7)
    c.drawString(
        18 * mm, 18 * mm,
        "Generated by FoodLoop for traceability. Not an official "
        "FSSAI certificate." + (" Demo data." if DEMO_MODE else ""))
    c.showPage()
    c.save()
    return buf.getvalue()
